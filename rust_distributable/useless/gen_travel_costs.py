#!/usr/bin/env python3
"""Generate the kingdom-transfer tables for ``crates/empire-game``.

Source: the game's own items file (``items_v<version>.json``), which the client downloads at
login. ``proxy_packet_monitor`` can save it (tick "Download login data", log in through the
proxy; it lands under ``web_data/login_data/files/empire-html5.goodgamestudios.com/default/items/``).

    python3 rust_distributable/utils/scripts/gen_travel_costs.py path/to/items_v787.03.json

Output (overwritten): ``crates/empire-game/src/generated/travel_costs.rs``

* ``TRAVEL_COSTS``: each unit's ``kingdomTravellingCost`` (coins before the target kingdom's tax).
* ``KINGDOM_TRANSFER_RATES``: each kingdom's ``unitTravelTaxRate`` (percent) and ``unitTravelTime`` (s).
* ``MINUTE_SKIPS``: the minute-skip items (``currencyMinutesSkipValues``), by their ``MS<n>`` key.

How the numbers combine: ``docs/game_infrastructure/kingdom_transfer_rules.md``.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

RUST_DIR = Path(__file__).resolve().parents[2]
OUT = RUST_DIR / "crates" / "empire-game" / "src" / "generated" / "travel_costs.rs"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1])
    items = json.loads(source.read_text(encoding="utf-8"))
    version = items.get("versionInfo", {}).get("version", {}).get("@value", "unknown")

    costs = sorted(
        (int(unit["wodID"]), int(unit["kingdomTravellingCost"]))
        for unit in items["units"]
        if unit.get("group") == "Unit" and int(unit.get("kingdomTravellingCost", 0) or 0) > 0
    )
    rates = sorted(
        (int(k["kID"]), int(k.get("unitTravelTaxRate", 0) or 0), int(k.get("unitTravelTime", 0) or 0))
        for k in items["kingdoms"]
    )
    skips = sorted(
        (int(row["MinuteSkipIndex"]), int(row["currencyID"]), int(row["MinutesSkipValue"]) * 60)
        for row in items["currencyMinutesSkipValues"]
    )

    lines = [
        "// @generated by utils/scripts/gen_travel_costs.py -- do not edit by hand.",
        f"// Source: items file version {version} (CastleItemXMLVersion).",
        "// Re-run: python3 rust_distributable/utils/scripts/gen_travel_costs.py <items.json>",
        "",
        "/// `(unit id, kingdomTravellingCost)` for every unit that has one, sorted by id.",
        f"pub static TRAVEL_COSTS: &[(i64, i64)] = &[  // {len(costs)} units",
    ]
    lines += [f"    ({unit}, {cost})," for unit, cost in costs]
    lines += [
        "];",
        "",
        "/// `(kingdom id, unitTravelTaxRate percent, unitTravelTime seconds)`, sorted by kingdom.",
        "pub static KINGDOM_TRANSFER_RATES: &[(i64, i64, i64)] = &[",
    ]
    lines += [f"    ({kid}, {tax}, {time})," for kid, tax, time in rates]
    lines += [
        "];",
        "",
        "/// `(key, currency id, seconds)` for the minute-skip items; the key is `MS` plus the 1-based index.",
        "pub static MINUTE_SKIPS: &[(&str, i64, i64)] = &[",
    ]
    lines += [f'    ("MS{index + 1}", {currency}, {seconds}),' for index, currency, seconds in skips]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(RUST_DIR)}: {len(costs)} unit costs, {len(rates)} kingdoms, {len(skips)} skips (items {version})")


if __name__ == "__main__":
    main()
